import { test, expect } from '@playwright/test';
import { fixedRunnerSeed, noJumpScore, opening } from './runnerScenario';
test('меню → сбор кассет → столкновение → повтор; без ошибок в браузере', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(`${message.text()} ${message.location().url}`); });
  await fixedRunnerSeed(page);
  await page.goto('/');
  await expect(page.getByRole('button', { name: 'Начать путь' })).toBeVisible();
  await page.screenshot({ path: 'test-results/menu.png' });
  await page.getByRole('button', { name: 'Начать путь' }).click();
  await page.getByRole('button', { name: 'Понятно, в путь' }).click();
  await expect(page.getByRole('heading', { name: 'Не в этот раз' })).toBeVisible({ timeout: 20000 });
  await expect(page.locator('.result-numbers strong').first()).toHaveText(String(noJumpScore));
  await page.screenshot({ path: 'test-results/game-over.png' });
  await page.getByRole('button', { name: 'Ещё раз' }).click();
  await expect(page.locator('.score strong')).toHaveText('0');
  await page.keyboard.down('Space');
  await page.waitForTimeout(100);
  await page.keyboard.up('Space');
  await expect(page.getByRole('button', { name: 'Пауза', exact: true })).toBeVisible();
  expect(errors).toEqual([]);
});
test('пауза сохраняет дистанцию, после поворота можно продолжить в обеих ориентациях', async ({ page }) => {
  await page.goto('/'); await page.getByRole('button', { name: 'Начать путь' }).click();
  await page.getByRole('button', { name: 'Понятно, в путь' }).click();
  await page.waitForTimeout(500);
  await page.getByRole('button', { name: 'Пауза', exact: true }).click();
  const distance = await page.locator('.distance span').textContent();
  await page.waitForTimeout(500);
  expect(await page.locator('.distance span').textContent()).toBe(distance);
  await page.getByRole('button', { name: 'Продолжить' }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByRole('button', { name: 'Продолжить' })).toBeVisible();
  await page.getByRole('button', { name: 'Продолжить' }).click();
  await expect(page.locator('main')).toHaveAttribute('data-paused', 'false');
  await page.setViewportSize({ width: 844, height: 390 });
  await expect(page.getByRole('button', { name: 'Продолжить' })).toBeVisible();
  await page.screenshot({ path: 'test-results/landscape-pause.png' });
});
test('сенсорные нажатия и кнопка звука доступны в мобильном окне', async ({ browser }) => {
  const context = await browser.newContext({ viewport: { width: 844, height: 390 }, hasTouch: true, isMobile: true });
  const page = await context.newPage();
  await page.goto('/'); await page.getByRole('button', { name: 'Начать путь' }).tap();
  await page.getByRole('button', { name: 'Понятно, в путь' }).tap();
  await page.getByRole('button', { name: 'Выключить звук' }).tap();
  const canvas = page.locator('canvas');
  const box = (await canvas.boundingBox())!;
  await page.touchscreen.tap(box.x + box.width * .5, box.y + box.height * .6);
  await expect(page.locator('.hud')).toBeVisible();
  await expect(page.getByRole('button', { name: 'Включить звук' })).toBeVisible();
  await context.close();
});
test('меню помещается в небольшой горизонтальный экран', async ({ page }) => {
  await page.setViewportSize({ width: 568, height: 320 });
  await page.goto('/');
  const start = page.getByRole('button', { name: 'Начать путь' });
  await expect(start).toBeVisible();
  const bounds = (await start.boundingBox())!;
  expect(bounds.y).toBeGreaterThan(45);
  expect(bounds.y + bounds.height).toBeLessThan(300);
  await page.screenshot({ path: 'test-results/small-menu.png' });
});
test('удержание пробела позволяет перепрыгнуть первое препятствие', async ({ page }) => {
  await fixedRunnerSeed(page);
  await page.goto('/');
  await page.getByRole('button', { name: 'Начать путь' }).click();
  await page.getByRole('button', { name: 'Понятно, в путь' }).click();
  await page.waitForFunction(distance => Number(document.querySelector('.distance span')?.textContent?.split('/')[0]) >= distance, opening.jumpAt);
  await page.keyboard.down('Space');
  await page.waitForFunction(distance => Number(document.querySelector('.distance span')?.textContent?.split('/')[0]) >= distance, opening.clearAt);
  await page.keyboard.up('Space');
  await page.getByRole('button', { name: 'Пауза', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Пауза', exact: true })).toBeVisible();
  await expect(page.getByRole('heading', { name: 'Не в этот раз' })).not.toBeVisible();
  await page.screenshot({ path: 'test-results/runner.png' });
});
